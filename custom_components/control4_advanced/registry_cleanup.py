"""Conservative cleanup of Director items removed from Home Assistant's registries."""

from __future__ import annotations

from collections.abc import Iterable
import logging
from typing import Any

from .const import DOMAIN


_LOGGER = logging.getLogger(__name__)


def _old_tidal_playlist_key(unique_id: str, host: str) -> tuple[int, int] | None:
    """Return the room and protocol from a version 0.1.16 playlist ID."""
    prefix = f"{host}_"
    if not unique_id.startswith(prefix):
        return None
    suffix = unique_id[len(prefix):]
    marker = "_tidal_playlist_"
    if marker not in suffix:
        return None
    room_id, protocol_id = suffix.rsplit(marker, 1)
    if not all(
        value.isascii() and value.isdecimal() and int(value) > 0
        for value in (room_id, protocol_id)
    ):
        return None
    return int(room_id), int(protocol_id)


def _director_id(unique_id: str, host: str) -> int | None:
    """Recognize only IDs generated by this integration for this Director."""
    prefix = f"{host}_"
    if not unique_id.startswith(prefix):
        return None
    suffix = unique_id[len(prefix):]
    for entity_suffix in (
        "_hold_mode", "_media_play", "_media_pause", "_media_stop",
        "_media_skip_rev", "_media_skip_fwd",
        "_tidal_account", "_tidal_playlist", "_room_volume",
    ):
        if suffix.endswith(entity_suffix):
            suffix = suffix[:-len(entity_suffix)]
            break
    old_playlist_marker = "_tidal_playlist_"
    if old_playlist_marker in suffix:
        room_id, protocol_id = suffix.rsplit(old_playlist_marker, 1)
        if protocol_id.isascii() and protocol_id.isdecimal():
            suffix = room_id
    if not suffix.isascii() or not suffix.isdecimal():
        return None
    device_id = int(suffix)
    return device_id if device_id > 0 else None


def tidal_playlist_registry_migration(
    entity_entries: Iterable[Any],
    *,
    config_entry_id: str,
    host: str,
    preferred_protocol_ids: dict[int, int],
) -> tuple[list[tuple[str, str]], list[str]]:
    """Plan the one-time collapse of per-account playlist registry entries."""
    owned = [
        entry
        for entry in entity_entries
        if entry.config_entry_id == config_entry_id
        and entry.platform == DOMAIN
        and isinstance(entry.unique_id, str)
    ]
    existing_unique_ids = {entry.unique_id for entry in owned}
    old_by_room: dict[int, list[tuple[Any, int]]] = {}
    for entry in owned:
        key = _old_tidal_playlist_key(entry.unique_id, host)
        if key is not None:
            room_id, protocol_id = key
            old_by_room.setdefault(room_id, []).append((entry, protocol_id))

    updates: list[tuple[str, str]] = []
    removals: list[str] = []
    for room_id, entries in old_by_room.items():
        new_unique_id = f"{host}_{room_id}_tidal_playlist"
        preferred_protocol_id = preferred_protocol_ids.get(room_id)
        keep = next(
            (
                entry
                for entry, protocol_id in entries
                if protocol_id == preferred_protocol_id
            ),
            None,
        )
        if new_unique_id in existing_unique_ids:
            keep = None
        if keep is not None:
            updates.append((keep.entity_id, new_unique_id))
        removals.extend(
            entry.entity_id for entry, _ in entries if entry is not keep
        )
    return updates, removals


def migrate_tidal_playlist_registry_entries(
    hass: Any,
    *,
    config_entry_id: str,
    host: str,
    preferred_protocol_ids: dict[int, int],
) -> None:
    """Migrate version 0.1.16 playlist entities before new platform setup."""
    from homeassistant.helpers import entity_registry as er

    registry = er.async_get(hass)
    updates, removals = tidal_playlist_registry_migration(
        er.async_entries_for_config_entry(registry, config_entry_id),
        config_entry_id=config_entry_id,
        host=host,
        preferred_protocol_ids=preferred_protocol_ids,
    )
    for entity_id, new_unique_id in updates:
        registry.async_update_entity(entity_id, new_unique_id=new_unique_id)
    for entity_id in removals:
        registry.async_remove(entity_id)
    if updates or removals:
        _LOGGER.info(
            "Migrated %d and removed %d superseded Control4 TIDAL playlist entities",
            len(updates), len(removals),
        )


def stale_registry_ids(
    entity_entries: Iterable[Any],
    device_entries: Iterable[Any],
    *,
    config_entry_id: str,
    host: str,
    first_inventory_ids: set[int],
    second_inventory_ids: set[int],
) -> tuple[list[str], list[str]]:
    """Plan removal only for owned IDs missing from two complete REST reads."""
    if not first_inventory_ids or not second_inventory_ids:
        return [], []

    def absent(unique_id: str) -> bool:
        device_id = _director_id(unique_id, host)
        return (
            device_id is not None
            and device_id not in first_inventory_ids
            and device_id not in second_inventory_ids
        )

    def obsolete_playlist(unique_id: str) -> bool:
        """Recognize per-account playlist IDs replaced in version 0.1.17."""
        return _old_tidal_playlist_key(unique_id, host) is not None

    stale_entities = [
        entity.entity_id
        for entity in entity_entries
        if entity.config_entry_id == config_entry_id
        and entity.platform == DOMAIN
        and isinstance(entity.unique_id, str)
        and (absent(entity.unique_id) or obsolete_playlist(entity.unique_id))
    ]
    stale_devices = [
        device.id
        for device in device_entries
        if device.config_entry_id == config_entry_id
        and len(device.identifiers) == 1
        and (
            identifier := next(iter(device.identifiers))
        )[0] == DOMAIN
        and isinstance(identifier[1], str)
        and absent(identifier[1])
    ]
    return stale_entities, stale_devices


def remove_stale_registry_entries(
    hass: Any,
    *,
    config_entry_id: str,
    host: str,
    first_inventory_ids: set[int],
    second_inventory_ids: set[int],
) -> None:
    """Remove confirmed stale entries only after successful platform setup."""
    from homeassistant.helpers import device_registry as dr, entity_registry as er

    entities = er.async_get(hass)
    devices = dr.async_get(hass)
    stale_entities, stale_devices = stale_registry_ids(
        er.async_entries_for_config_entry(entities, config_entry_id),
        dr.async_entries_for_config_entry(devices, config_entry_id),
        config_entry_id=config_entry_id,
        host=host,
        first_inventory_ids=first_inventory_ids,
        second_inventory_ids=second_inventory_ids,
    )
    for entity_id in stale_entities:
        entities.async_remove(entity_id)
    for device_id in stale_devices:
        if devices.async_get(device_id) is not None:
            devices.async_remove_device(device_id)
    if stale_entities or stale_devices:
        _LOGGER.info(
            "Removed %d stale Control4 entities and %d devices from Home Assistant registries",
            len(stale_entities), len(stale_devices),
        )
